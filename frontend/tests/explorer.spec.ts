test('mobile map, draggable bottom sheet, marker selection and keyboard dialogs', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  expect((await page.request.post('/api/auth/register',{data:{email:`mobile-map-${Date.now()}@example.com`,password:'mobile-map-password',display_name:'Mobile Explorer'}})).status()).toBe(201);
  await page.reload();
  await expect(page.getByRole('heading',{name:'Your next ride is out there.'})).toBeVisible();
  const sheet=page.getByRole('region',{name:'Discovery results'});
  const before=await sheet.boundingBox();
  const handle=page.getByRole('button',{name:'Expand discovery results',exact:true});
  const box=await handle.boundingBox();
  await page.mouse.move(box!.x+box!.width/2,box!.y+box!.height/2);
  await page.mouse.down();await page.mouse.move(box!.x+box!.width/2,box!.y-230,{steps:12});await page.mouse.up();
  await expect(page.getByRole('button',{name:'Collapse discovery results',exact:true})).toBeVisible();
  expect((await sheet.boundingBox())!.height).toBeGreaterThan(before!.height);
  await page.getByRole('tab',{name:/People/}).click();
  await page.getByRole('button',{name:'Preview Ananya R.',exact:true}).click();
  await expect(page.getByRole('complementary',{name:'Ananya R. preview'})).toContainText('never a live location');
  await page.getByRole('button',{name:'View full profile'}).click();
  await expect(page.getByRole('button',{name:'Close dialog'})).toBeFocused();
  await page.keyboard.press('Escape');await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button',{name:'Close map preview'}).click();
  await page.getByRole('button',{name:'Collapse discovery results',exact:true}).click();
  await page.getByRole('tab',{name:/All/}).click();
  await expect(page.locator('.leaflet-marker-icon[title="Semmozhi Poonga — park"]')).toBeVisible();
  await page.locator('.leaflet-marker-icon[title="Semmozhi Poonga — park"]').click();
  await expect(page.getByRole('complementary',{name:'Semmozhi Poonga preview'})).toBeVisible();
  await page.getByRole('button',{name:'Close map preview'}).click();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/mobile-discovery.png',fullPage:true});
  expect((await page.request.delete('/api/account')).status()).toBe(204);
});
